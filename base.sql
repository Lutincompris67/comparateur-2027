-- Crée une source et renvoie son identifiant. Si une source porte déjà la même
-- adresse web, c'est elle qui est renvoyée : une source n'est saisie qu'une fois.
create or replace function public.creer_source(
  p_auteurs text, p_titre text, p_type text, p_organisme text,
  p_date_publication text, p_url text, p_date_consultation text
) returns text
language plpgsql security definer set search_path = '' as $$
declare
  v_url  text := lower(regexp_replace(btrim(coalesce(p_url, '')), '/+$', ''));
  v_base text;
  v_an   text;
  v_id   text;
  n      integer := 1;
begin
  if not public.a_un_role() then
    raise exception 'Action réservée aux contributeurs.';
  end if;
  if btrim(coalesce(p_titre, '')) = '' then
    raise exception 'Le titre de la source est obligatoire.';
  end if;
  if v_url <> '' then
    select s.id into v_id from public.sources s
     where lower(regexp_replace(btrim(s.url), '/+$', '')) = v_url limit 1;
    if v_id is not null then return v_id; end if;
  end if;

  v_base := split_part(btrim(coalesce(nullif(btrim(p_organisme), ''), nullif(btrim(p_auteurs), ''), p_titre)), ' ', 1);
  v_base := translate(lower(v_base), 'àâäáãåçéèêëíìîïñóòôöõúùûüýÿ', 'aaaaaaceeeeiiiinooooouuuuyy');
  v_base := left(upper(regexp_replace(v_base, '[^a-z0-9]', '', 'g')), 12);
  if v_base = '' then v_base := 'SOURCE'; end if;
  v_an := coalesce(substring(coalesce(p_date_publication, '') from '(\d{4})'), to_char(now(), 'YYYY'));
  loop
    v_id := v_base || '-' || v_an || '-' || lpad(n::text, 2, '0');
    exit when not exists (select 1 from public.sources s where s.id = v_id);
    n := n + 1;
  end loop;

  insert into public.sources (id, registre, auteurs, titre, type, organisme,
                              date_publication, url, date_consultation, cree_par)
  values (v_id, 'analyse', btrim(coalesce(p_auteurs, '')), btrim(p_titre), btrim(coalesce(p_type, '')),
          btrim(coalesce(p_organisme, '')), btrim(coalesce(p_date_publication, '')),
          btrim(coalesce(p_url, '')), btrim(coalesce(p_date_consultation, '')), auth.uid());
  return v_id;
end $$;

-- Enregistre une image déjà téléversée et renvoie l'identifiant de la figure.
create or replace function public.creer_figure_image(
  p_titre text, p_alt text, p_credit text, p_url text
) returns text
language plpgsql security definer set search_path = '' as $$
declare v_id text;
begin
  if not public.a_un_role() then
    raise exception 'Action réservée aux contributeurs.';
  end if;
  if btrim(coalesce(p_titre, '')) = '' or btrim(coalesce(p_alt, '')) = '' then
    raise exception 'Le titre et la description de l''image sont obligatoires.';
  end if;
  if btrim(coalesce(p_credit, '')) = '' then
    raise exception 'La source des données de l''image est obligatoire.';
  end if;
  if p_url !~ '^https://[a-z0-9]+\.supabase\.co/storage/v1/object/public/figures/[A-Za-z0-9._/-]+$' then
    raise exception 'Adresse d''image inattendue.';
  end if;
  v_id := 'FIG-image-' || lpad(nextval('public.figures_numero')::text, 4, '0');
  insert into public.figures (id, type, titre, alt, credit, url, cree_par)
  values (v_id, 'image', btrim(p_titre), btrim(p_alt), btrim(p_credit), p_url, auth.uid());
  return v_id;
end $$;

