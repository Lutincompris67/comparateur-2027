create or replace function public.donnees_publiques() returns jsonb
language sql stable security definer set search_path = '' as $$
with
ed as (
  select * from public.editorial where publie
),
figs as (
  select f.* from public.figures f
  where exists (select 1 from ed where position('{{' || f.id || '}}' in ed.texte) > 0)
),
src as (
  select s.* from public.sources s
  where s.registre = 'programme'
     or exists (select 1 from ed where s.id = any (ed.sources))
     or exists (select 1 from figs where s.id = any (figs.sources))
),
suj as (
  select s.id, s.thematique, s.ordre, s.aussi_dans, t.ordre as ordre_theme,
         jsonb_build_object(
           'id', s.id, 'label', s.libelle,
           'positions', coalesce((select jsonb_object_agg(p.candidat, p.texte)
                                  from public.positions p where p.sujet_id = s.id), '{}'::jsonb))
         || case when cardinality(s.aussi_dans) > 0
                 then jsonb_build_object('aliasIn', to_jsonb(s.aussi_dans)) else '{}'::jsonb end as objet
  from public.sujets s join public.thematiques t on t.nom = s.thematique
),
place as (
  -- chaque sujet dans sa thématique d'origine, puis dans celles qui l'empruntent
  select s.thematique as theme, 0 as emprunt, s.ordre_theme, s.ordre, s.objet from suj s
  union all
  select a.cible, 1, s.ordre_theme, s.ordre, s.objet
  from suj s cross join lateral unnest(s.aussi_dans) as a(cible)
  where a.cible <> s.thematique
)
select jsonb_build_object(
  'meta', jsonb_build_object(
    'title', 'Comparateur 2027',
    'generated', to_char(coalesce(greatest((select max(maj) from public.positions),
                                           (select max(maj) from ed)), now())
                         at time zone 'Europe/Paris', 'YYYY-MM-DD')),
  'candidates', coalesce((select jsonb_agg(c.nom order by c.ordre, c.nom) from public.candidats c), '[]'::jsonb),
  'themes', coalesce((
    select jsonb_agg(jsonb_build_object(
             'name', t.nom,
             'subjects', coalesce((select jsonb_agg(p.objet order by p.emprunt, p.ordre_theme, p.ordre)
                                   from place p where p.theme = t.nom), '[]'::jsonb))
           order by t.ordre, t.nom)
    from public.thematiques t), '[]'::jsonb),
  'editorial', coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', e.sujet_id, 'type', e.type, 'author', e.auteur, 'initials', e.initiales,
             'age', e.age, 'text', e.texte, 'sources', to_jsonb(e.sources))
           order by e.id)
    from ed e), '[]'::jsonb),
  'bibliography', coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', s.id, 'registre', s.registre, 'authors', s.auteurs, 'title', s.titre,
             'type', s.type, 'org', s.organisme, 'date', s.date_publication,
             'url', s.url, 'consulted', s.date_consultation)
           order by s.ordre)
    from src s), '[]'::jsonb),
  'figures', coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', f.id, 'type', f.type, 'title', f.titre, 'unit', f.unite,
             'axisMin', f.axe_min, 'axisMax', f.axe_max, 'note', f.note,
             'sources', to_jsonb(f.sources), 'edition', f.edition, 'file', f.fichier,
             'alt', f.alt, 'series', f.series, 'url', f.url, 'credit', f.credit)
           order by f.ordre)
    from figs f), '[]'::jsonb)
)
$$;

