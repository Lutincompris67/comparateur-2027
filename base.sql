-- =====================================================================
-- Comparateur 2027 — base de données (Supabase / PostgreSQL)
--
-- Mode d'emploi : dans Supabase, ouvrir « SQL Editor », coller CE FICHIER
-- EN ENTIER, cliquer « Run ». Le script peut être relancé sans risque :
-- il ne supprime aucune donnée.
--
-- Règles portées par la base elle-même (et non par les pages web) :
--   * seul un contributeur du circuit concerné peut déposer ;
--   * un dépôt n'est en ligne qu'après validation par un mainteneur,
--     qui ne peut pas être le déposant ;
--   * un mainteneur peut toujours dépublier, jamais publier seul ;
--   * les visiteurs lisent sans compte, et ne voient que le contenu publié ;
--   * un verbatim déposé s'AJOUTE à la case (assemblage fait à la validation),
--     sauf s'il est déclaré comme correction du texte en ligne : il ne remplace
--     alors la case que si elle n'a pas changé depuis le dépôt (version du 18/10/2026).
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. TABLES
-- ---------------------------------------------------------------------

-- Une ligne par personne connectée via Discord. Les quatre cases sont les droits.
create table if not exists public.profils (
  id          uuid primary key references auth.users(id) on delete cascade,
  pseudo      text not null default '',
  analyses    boolean not null default false,
  partis_pris boolean not null default false,
  verbatims   boolean not null default false,
  mainteneur  boolean not null default false,
  cree_le     timestamptz not null default now()
);

-- Structure de la grille
create table if not exists public.candidats (
  nom   text primary key,
  ordre integer not null default 0
);
create table if not exists public.thematiques (
  nom   text primary key,
  ordre integer not null default 0
);
create table if not exists public.sujets (
  id         text primary key,
  libelle    text not null,
  thematique text not null references public.thematiques(nom) on update cascade,
  ordre      integer not null default 0,
  aussi_dans text[] not null default '{}'
);

-- Contenu en ligne : verbatims (une case = un sujet x un candidat)
create table if not exists public.positions (
  sujet_id text not null references public.sujets(id) on update cascade,
  candidat text not null references public.candidats(nom) on update cascade,
  texte    text not null,
  maj      timestamptz not null default now(),
  primary key (sujet_id, candidat)
);

-- Contenu en ligne : analyses et partis pris
create table if not exists public.editorial (
  id        bigint generated always as identity primary key,
  sujet_id  text not null references public.sujets(id) on update cascade,
  type      text not null check (type in ('analyse', 'parti pris')),
  auteur    text not null default '',
  initiales text not null default '',
  age       integer,
  texte     text not null,
  sources   text[] not null default '{}',
  publie    boolean not null default true,
  cree_le   timestamptz not null default now(),
  maj       timestamptz not null default now()
);

-- Bibliographie
create table if not exists public.sources (
  id                text primary key,
  registre          text not null default 'analyse' check (registre in ('programme', 'analyse')),
  auteurs           text not null default '',
  titre             text not null default '',
  type              text not null default '',
  organisme         text not null default '',
  date_publication  text not null default '',
  url               text not null default '',
  date_consultation text not null default '',
  ordre             bigint generated by default as identity,
  cree_par          uuid references public.profils(id) on delete set null,
  cree_le           timestamptz not null default now()
);

-- Figures : graphiques (données dans « series ») ou images (adresse dans « url »)
create table if not exists public.figures (
  id       text primary key,
  type     text not null check (type in ('courbe', 'barres', 'tableau', 'image')),
  titre    text not null default '',
  unite    text not null default '',
  axe_min  numeric,
  axe_max  numeric,
  note     text not null default '',
  sources  text[] not null default '{}',
  edition  text not null default '',
  fichier  text not null default '',
  alt      text not null default '',
  series   jsonb not null default '[]',
  url      text not null default '',
  credit   text not null default '',
  ordre    bigint generated by default as identity,
  cree_par uuid references public.profils(id) on delete set null,
  cree_le  timestamptz not null default now()
);
create sequence if not exists public.figures_numero;

-- File des dépôts (et historique : rien n'y est jamais effacé)
create table if not exists public.depots (
  id           bigint generated always as identity primary key,
  circuit      text not null check (circuit in ('analyse', 'parti pris', 'verbatim')),
  sujet_id     text not null references public.sujets(id) on update cascade,
  candidat     text references public.candidats(nom) on update cascade,
  auteur       text not null default '',
  initiales    text not null default '',
  age          integer,
  texte        text not null,
  sources      text[] not null default '{}',
  relecteurs   text[] not null default '{}',
  remplace     bigint references public.editorial(id),
  suite_de     bigint references public.depots(id),
  statut       text not null default 'en attente' check (statut in ('en attente', 'publié', 'refusé')),
  motif        text,
  depose_par   uuid references public.profils(id) on delete set null,
  depose_le    timestamptz not null default now(),
  traite_par   uuid references public.profils(id) on delete set null,
  traite_le    timestamptz,
  editorial_id bigint references public.editorial(id)
);
create index if not exists depots_statut on public.depots (statut, depose_le);

-- Verbatims (18/10/2026) : un dépôt s'ajoute à la case, ou la corrige.
--   mode = 'ajout'        : le texte déposé est ajouté à la suite de la case, après « — ».
--   mode = 'remplacement' : le texte déposé remplace la case ; texte_base garde le texte
--                           que le déposant avait sous les yeux, pour refuser la validation
--                           si la case a changé entre-temps.
-- Les dépôts antérieurs gardent mode vide : ils remplacent la case, comme avant.
alter table public.depots add column if not exists mode text check (mode in ('ajout', 'remplacement'));
alter table public.depots add column if not exists texte_base text;

-- Signalements envoyés par les visiteurs
create table if not exists public.signalements (
  id       bigint generated always as identity primary key,
  cree_le  timestamptz not null default now(),
  sujet_id text check (sujet_id is null or char_length(sujet_id) <= 120),
  message  text not null check (char_length(message) between 5 and 3000),
  contact  text check (contact is null or char_length(contact) <= 200),
  traite   boolean not null default false
);

-- Journal : qui a validé, refusé, dépublié, changé un droit, importé
create table if not exists public.journal (
  id     bigint generated always as identity primary key,
  quand  timestamptz not null default now(),
  qui    uuid references public.profils(id) on delete set null,
  pseudo text not null default '',
  action text not null,
  detail jsonb not null default '{}'
);

-- ---------------------------------------------------------------------
-- 2. FONCTIONS D'APPUI
-- ---------------------------------------------------------------------

create or replace function public.est_mainteneur() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((select p.mainteneur from public.profils p where p.id = auth.uid()), false)
$$;

-- Vrai si la personne connectée a au moins un droit (un simple compte Discord ne suffit pas).
create or replace function public.a_un_role() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((select p.analyses or p.partis_pris or p.verbatims or p.mainteneur
                   from public.profils p where p.id = auth.uid()), false)
$$;

create or replace function public._journal(p_action text, p_detail jsonb) returns void
language sql security definer set search_path = '' as $$
  insert into public.journal (qui, pseudo, action, detail)
  values (auth.uid(), coalesce((select p.pseudo from public.profils p where p.id = auth.uid()), ''), p_action, p_detail)
$$;

-- Création automatique du profil à la première connexion Discord (sans aucun droit).
create or replace function public.nouveau_profil() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profils (id, pseudo)
  values (new.id, left(coalesce(
            nullif(new.raw_user_meta_data -> 'custom_claims' ->> 'global_name', ''),
            nullif(new.raw_user_meta_data ->> 'full_name', ''),
            nullif(new.raw_user_meta_data ->> 'name', ''),
            'Sans nom'), 80))
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists comparateur_nouveau_profil on auth.users;
create trigger comparateur_nouveau_profil after insert on auth.users
  for each row execute function public.nouveau_profil();

-- ---------------------------------------------------------------------
-- 3. LE DÉPÔT : contrôles appliqués à chaque texte déposé
-- ---------------------------------------------------------------------

create or replace function public.depots_controle() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_profil  public.profils;
  v_relus   text[];
  v_minimum integer;
  v_manque  text;
  v_actuel  text;
begin
  select * into v_profil from public.profils where id = auth.uid();
  if not found then
    raise exception 'Vous devez être connecté pour déposer un texte.';
  end if;
  if (new.circuit = 'analyse' and not v_profil.analyses)
     or (new.circuit = 'parti pris' and not v_profil.partis_pris)
     or (new.circuit = 'verbatim' and not v_profil.verbatims) then
    raise exception 'Votre compte n''a pas le droit de déposer dans le circuit « % ».', new.circuit;
  end if;

  -- Champs que le déposant ne choisit pas
  new.depose_par := auth.uid();
  new.depose_le := now();
  new.statut := 'en attente';
  new.motif := null;
  new.traite_par := null;
  new.traite_le := null;
  new.editorial_id := null;

  new.texte := btrim(new.texte, E' \t\r\n');
  if new.texte = '' then
    raise exception 'Le texte est vide.';
  end if;

  -- Relecteurs : noms distincts, non vides
  select coalesce(array_agg(distinct btrim(r)), '{}') into v_relus
  from unnest(new.relecteurs) as r where btrim(r) <> '';
  new.relecteurs := v_relus;
  v_minimum := case when new.circuit = 'verbatim' or new.remplace is not null or new.suite_de is not null
                    then 1 else 2 end;
  if cardinality(v_relus) < v_minimum then
    raise exception 'Il faut indiquer % relecteur(s) distinct(s) pour ce dépôt.', v_minimum;
  end if;

  if new.circuit = 'verbatim' then
    if new.candidat is null then
      raise exception 'Un verbatim doit être rattaché à un candidat.';
    end if;
    new.auteur := ''; new.initiales := ''; new.age := null;
    new.sources := '{}'; new.remplace := null;

    -- Ajout (par défaut) ou correction du texte en ligne
    new.mode := coalesce(new.mode, 'ajout');
    if new.mode = 'remplacement' then
      select p.texte into v_actuel from public.positions p
       where p.sujet_id = new.sujet_id and p.candidat = new.candidat;
      if not found then
        raise exception 'Cette case est vide : il n''y a rien à corriger. Déposez votre texte comme un ajout.';
      end if;
      if new.texte_base is distinct from v_actuel then
        raise exception 'La case a changé pendant votre saisie : rechargez la page et repartez du texte en ligne.';
      end if;
      if new.texte = v_actuel then
        raise exception 'Le texte déposé est identique au texte en ligne.';
      end if;
    else
      new.texte_base := null;
    end if;
  else
    new.candidat := null;
    new.mode := null; new.texte_base := null;
    new.auteur := btrim(new.auteur);
    new.initiales := btrim(new.initiales);
    if new.auteur = '' then
      raise exception 'Le nom de l''auteur (ou son pseudonyme) est obligatoire.';
    end if;
    if new.circuit = 'parti pris' then
      if new.age is null or new.age < 18 then
        raise exception 'L''auteur d''un parti pris doit être majeur : indiquez son âge.';
      end if;
    else
      new.age := null;
    end if;
    if new.remplace is not null and not exists (
         select 1 from public.editorial e
         where e.id = new.remplace and e.sujet_id = new.sujet_id and e.type = new.circuit) then
      raise exception 'Le texte à corriger est introuvable sur ce sujet.';
    end if;
    select s into v_manque from unnest(new.sources) as s
      where not exists (select 1 from public.sources b where b.id = s) limit 1;
    if v_manque is not null then
      raise exception 'La source « % » n''existe pas dans la bibliographie.', v_manque;
    end if;
  end if;

  if new.suite_de is not null and not exists (
       select 1 from public.depots d
       where d.id = new.suite_de and d.statut = 'refusé' and d.circuit = new.circuit) then
    raise exception 'Le dépôt refusé auquel celui-ci fait suite est introuvable.';
  end if;
  return new;
end $$;

drop trigger if exists depots_controle on public.depots;
create trigger depots_controle before insert on public.depots
  for each row execute function public.depots_controle();

