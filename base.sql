create or replace function public.valider_depot(p_id bigint) returns void
language plpgsql security definer set search_path = '' as $$
declare
  d        public.depots;
  v_id     bigint;
  v_actuel text;
  v_existe boolean;
begin
  if not public.est_mainteneur() then
    raise exception 'Action réservée aux mainteneurs.';
  end if;
  select * into d from public.depots where id = p_id for update;
  if not found then raise exception 'Dépôt introuvable.'; end if;
  if d.statut <> 'en attente' then
    raise exception 'Ce dépôt a déjà été traité (%).', d.statut;
  end if;
  if d.depose_par = auth.uid() then
    raise exception 'Vous ne pouvez pas valider un texte que vous avez vous-même déposé.';
  end if;

  if d.circuit = 'verbatim' then
    select p.texte into v_actuel from public.positions p
     where p.sujet_id = d.sujet_id and p.candidat = d.candidat for update;
    v_existe := found;

    if d.mode = 'ajout' then
      -- Le texte s'ajoute à ce qui est en ligne AU MOMENT de la validation.
      insert into public.positions (sujet_id, candidat, texte, maj)
      values (d.sujet_id, d.candidat, d.texte, now())
      on conflict (sujet_id, candidat)
        do update set texte = public.positions.texte || ' — ' || excluded.texte, maj = now();
    elsif d.mode = 'remplacement' then
      if not v_existe or v_actuel is distinct from d.texte_base then
        raise exception 'La case a changé depuis ce dépôt : un autre texte y a été validé entre-temps. Refusez ce dépôt en demandant de repartir du texte en ligne.';
      end if;
      update public.positions set texte = d.texte, maj = now()
       where sujet_id = d.sujet_id and candidat = d.candidat;
    else
      -- Dépôts antérieurs au 18/10/2026 : remplacement simple, comme avant.
      insert into public.positions (sujet_id, candidat, texte, maj)
      values (d.sujet_id, d.candidat, d.texte, now())
      on conflict (sujet_id, candidat) do update set texte = excluded.texte, maj = now();
    end if;
  elsif d.remplace is not null then
    update public.editorial
       set auteur = d.auteur, initiales = d.initiales, age = d.age, texte = d.texte,
           sources = d.sources, publie = true, maj = now()
     where id = d.remplace;
    v_id := d.remplace;
  else
    insert into public.editorial (sujet_id, type, auteur, initiales, age, texte, sources)
    values (d.sujet_id, d.circuit, d.auteur, d.initiales, d.age, d.texte, d.sources)
    returning id into v_id;
  end if;

  update public.depots
     set statut = 'publié', traite_par = auth.uid(), traite_le = now(), editorial_id = v_id
   where id = p_id;
  perform public._journal('validation', jsonb_build_object(
    'depot', p_id, 'circuit', d.circuit, 'sujet', d.sujet_id, 'candidat', d.candidat,
    'mode', d.mode, 'texte_avant', v_actuel));
end $$;

create or replace function public.refuser_depot(p_id bigint, p_motif text) returns void
language plpgsql security definer set search_path = '' as $$
declare d public.depots;
begin
  if not public.est_mainteneur() then
    raise exception 'Action réservée aux mainteneurs.';
  end if;
  if btrim(coalesce(p_motif, '')) = '' then
    raise exception 'Un refus doit être accompagné d''un motif.';
  end if;
  select * into d from public.depots where id = p_id for update;
  if not found then raise exception 'Dépôt introuvable.'; end if;
  if d.statut <> 'en attente' then
    raise exception 'Ce dépôt a déjà été traité (%).', d.statut;
  end if;
  update public.depots
     set statut = 'refusé', motif = btrim(p_motif), traite_par = auth.uid(), traite_le = now()
   where id = p_id;
  perform public._journal('refus', jsonb_build_object(
    'depot', p_id, 'circuit', d.circuit, 'sujet', d.sujet_id, 'motif', btrim(p_motif)));
end $$;

-- Dépublier une analyse ou un parti pris (le texte est conservé, mais n'est plus en ligne).
create or replace function public.depublier_editorial(p_id bigint, p_motif text) returns void
language plpgsql security definer set search_path = '' as $$
declare e public.editorial;
begin
  if not public.est_mainteneur() then
    raise exception 'Action réservée aux mainteneurs.';
  end if;
  update public.editorial set publie = false, maj = now() where id = p_id returning * into e;
  if not found then raise exception 'Texte introuvable.'; end if;
  perform public._journal('dépublication', jsonb_build_object(
    'editorial', p_id, 'type', e.type, 'sujet', e.sujet_id, 'motif', coalesce(p_motif, '')));
end $$;

-- Dépublier un verbatim : la case redevient « À venir ». Le texte retiré est gardé au journal.
create or replace function public.depublier_position(p_sujet text, p_candidat text, p_motif text) returns void
language plpgsql security definer set search_path = '' as $$
declare v_texte text;
begin
  if not public.est_mainteneur() then
    raise exception 'Action réservée aux mainteneurs.';
  end if;
  delete from public.positions where sujet_id = p_sujet and candidat = p_candidat returning texte into v_texte;
  if not found then raise exception 'Cette case est déjà vide.'; end if;
  perform public._journal('dépublication', jsonb_build_object(
    'type', 'verbatim', 'sujet', p_sujet, 'candidat', p_candidat,
    'motif', coalesce(p_motif, ''), 'texte', v_texte));
end $$;

create or replace function public.definir_roles(
  p_id uuid, p_analyses boolean, p_partis_pris boolean, p_verbatims boolean, p_mainteneur boolean
) returns void
language plpgsql security definer set search_path = '' as $$
declare v_pseudo text;
begin
  if not public.est_mainteneur() then
    raise exception 'Action réservée aux mainteneurs.';
  end if;
  if not p_mainteneur and not exists (
       select 1 from public.profils where mainteneur and id <> p_id) then
    raise exception 'Impossible : il ne resterait plus aucun mainteneur.';
  end if;
  update public.profils
     set analyses = p_analyses, partis_pris = p_partis_pris,
         verbatims = p_verbatims, mainteneur = p_mainteneur
   where id = p_id returning pseudo into v_pseudo;
  if not found then raise exception 'Profil introuvable.'; end if;
  perform public._journal('droits', jsonb_build_object(
    'profil', p_id, 'pseudo', v_pseudo, 'analyses', p_analyses, 'partis_pris', p_partis_pris,
    'verbatims', p_verbatims, 'mainteneur', p_mainteneur));
end $$;

create or replace function public.traiter_signalement(p_id bigint, p_traite boolean) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not public.est_mainteneur() then
    raise exception 'Action réservée aux mainteneurs.';
  end if;
  update public.signalements set traite = p_traite where id = p_id;
end $$;

-- Supprimer un signalement : seulement s'il est marqué « traité ». Noté au journal.
create or replace function public.supprimer_signalement(p_id bigint) returns void
language plpgsql security definer set search_path = '' as $$
declare s public.signalements;
begin
  if not public.est_mainteneur() then
    raise exception 'Action réservée aux mainteneurs.';
  end if;
  select * into s from public.signalements where id = p_id for update;
  if not found then raise exception 'Signalement introuvable.'; end if;
  if not s.traite then
    raise exception 'Seul un signalement marqué comme traité peut être supprimé.';
  end if;
  delete from public.signalements where id = p_id;
  perform public._journal('suppression de signalement', jsonb_build_object(
    'signalement', p_id, 'sujet', s.sujet_id, 'recu_le', s.cree_le, 'message', s.message));
end $$;

-- Supprime d'un coup tous les signalements traités ; renvoie leur nombre.
create or replace function public.supprimer_signalements_traites() returns integer
language plpgsql security definer set search_path = '' as $$
declare n integer;
begin
  if not public.est_mainteneur() then
    raise exception 'Action réservée aux mainteneurs.';
  end if;
  delete from public.signalements where traite;
  get diagnostics n = row_count;
  if n > 0 then
    perform public._journal('suppression de signalements', jsonb_build_object('nombre', n));
  end if;
  return n;
end $$;

