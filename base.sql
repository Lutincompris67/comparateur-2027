-- Applique la STRUCTURE d'un classeur (candidats, thématiques, sujets, emprunts)
-- sans jamais toucher à un texte. Fonction interne, appelée par les deux imports.
create or replace function public._appliquer_structure(d jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_doublon      text;
  v_ajoutes      integer;
  v_conserves    jsonb;
  v_cand_gardes  jsonb;
  v_supprimes    integer;
begin
  if jsonb_typeof(d -> 'thematiques') <> 'array' or jsonb_array_length(d -> 'thematiques') < 3 then
    raise exception 'Ce fichier ne ressemble pas au classeur source (moins de trois thématiques).';
  end if;

  drop table if exists pg_temp._s;
  create temporary table _s on commit drop as
    select s ->> 'id' as id, s ->> 'libelle' as libelle, t ->> 'nom' as thematique,
           (tord * 1000 + sord)::integer as rang, sord::integer as ordre,
           coalesce(array(select jsonb_array_elements_text(
             case when jsonb_typeof(s -> 'aussi_dans') = 'array' then s -> 'aussi_dans' else '[]'::jsonb end)), '{}') as aussi_dans
    from jsonb_array_elements(d -> 'thematiques') with ordinality as x(t, tord),
         jsonb_array_elements(t -> 'sujets') with ordinality as y(s, sord);

  select id into v_doublon from _s group by id having count(*) > 1 limit 1;
  if v_doublon is not null then
    raise exception 'ID_sujet en double dans le fichier : %', v_doublon;
  end if;
  if exists (select 1 from _s where coalesce(id, '') = '') then
    raise exception 'Le fichier contient un sujet sans ID_sujet.';
  end if;

  insert into public.candidats (nom, ordre)
    select c, ord::integer from jsonb_array_elements_text(d -> 'candidats') with ordinality as x(c, ord)
  on conflict (nom) do update set ordre = excluded.ordre;

  insert into public.thematiques (nom, ordre)
    select t ->> 'nom', ord::integer from jsonb_array_elements(d -> 'thematiques') with ordinality as x(t, ord)
  on conflict (nom) do update set ordre = excluded.ordre;

  select count(*) into v_ajoutes from _s where not exists (select 1 from public.sujets s where s.id = _s.id);

  insert into public.sujets (id, libelle, thematique, ordre, aussi_dans)
    select id, coalesce(nullif(libelle, ''), id), thematique, ordre, aussi_dans from _s
  on conflict (id) do update
    set libelle = excluded.libelle, thematique = excluded.thematique,
        ordre = excluded.ordre, aussi_dans = excluded.aussi_dans;

  -- Sujets absents du fichier : supprimés s'ils sont vides, conservés et signalés sinon.
  select coalesce(jsonb_agg(s.id order by s.id), '[]'::jsonb) into v_conserves
  from public.sujets s
  where not exists (select 1 from _s where _s.id = s.id)
    and (exists (select 1 from public.positions p where p.sujet_id = s.id)
      or exists (select 1 from public.editorial e where e.sujet_id = s.id)
      or exists (select 1 from public.depots x where x.sujet_id = s.id));

  delete from public.sujets s
  where not exists (select 1 from _s where _s.id = s.id)
    and not exists (select 1 from public.positions p where p.sujet_id = s.id)
    and not exists (select 1 from public.editorial e where e.sujet_id = s.id)
    and not exists (select 1 from public.depots x where x.sujet_id = s.id);
  get diagnostics v_supprimes = row_count;

  delete from public.thematiques t
  where not exists (select 1 from jsonb_array_elements(d -> 'thematiques') as x(j) where j ->> 'nom' = t.nom)
    and not exists (select 1 from public.sujets s where s.thematique = t.nom);

  select coalesce(jsonb_agg(c.nom order by c.ordre), '[]'::jsonb) into v_cand_gardes
  from public.candidats c
  where not exists (select 1 from jsonb_array_elements_text(d -> 'candidats') as x(n) where n = c.nom)
    and (exists (select 1 from public.positions p where p.candidat = c.nom)
      or exists (select 1 from public.depots x where x.candidat = c.nom));

  delete from public.candidats c
  where not exists (select 1 from jsonb_array_elements_text(d -> 'candidats') as x(n) where n = c.nom)
    and not exists (select 1 from public.positions p where p.candidat = c.nom)
    and not exists (select 1 from public.depots x where x.candidat = c.nom);

  return jsonb_build_object(
    'thematiques', (select count(*) from public.thematiques),
    'sujets', (select count(*) from public.sujets),
    'candidats', (select count(*) from public.candidats),
    'sujets_ajoutes', v_ajoutes,
    'sujets_supprimes', v_supprimes,
    'sujets_conserves', v_conserves,
    'candidats_conserves', v_cand_gardes,
    'emprunts_invalides', (
      select coalesce(jsonb_agg(s.id || ' → ' || a.cible), '[]'::jsonb)
      from public.sujets s cross join lateral unnest(s.aussi_dans) as a(cible)
      where not exists (select 1 from public.thematiques t where t.nom = a.cible)));
end $$;

-- Réimport depuis Excel : la structure seulement.
create or replace function public.import_structure(d jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare r jsonb;
begin
  if not public.est_mainteneur() then
    raise exception 'Action réservée aux mainteneurs.';
  end if;
  r := public._appliquer_structure(d);
  perform public._journal('import de structure', r);
  return r;
end $$;

-- Import initial : structure ET contenus. Ne fonctionne que sur une base encore vide,
-- pour qu'il ne puisse jamais servir à publier en contournant la validation.
create or replace function public.import_initial(d jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare r jsonb;
begin
  if not public.est_mainteneur() then
    raise exception 'Action réservée aux mainteneurs.';
  end if;
  if exists (select 1 from public.positions) or exists (select 1 from public.editorial) then
    raise exception 'La base contient déjà des textes : l''import initial n''est possible qu''une fois.';
  end if;
  r := public._appliquer_structure(d);

  insert into public.positions (sujet_id, candidat, texte)
    select s ->> 'id', p.key, p.value
    from jsonb_array_elements(d -> 'thematiques') as x(t),
         jsonb_array_elements(t -> 'sujets') as y(s),
         jsonb_each_text(coalesce(s -> 'positions', '{}'::jsonb)) as p
    where btrim(p.value) <> '';

  insert into public.sources (id, registre, auteurs, titre, type, organisme,
                              date_publication, url, date_consultation)
    select b ->> 'id', coalesce(nullif(b ->> 'registre', ''), 'analyse'), coalesce(b ->> 'auteurs', ''),
           coalesce(b ->> 'titre', ''), coalesce(b ->> 'type', ''), coalesce(b ->> 'organisme', ''),
           coalesce(b ->> 'date_publication', ''), coalesce(b ->> 'url', ''), coalesce(b ->> 'date_consultation', '')
    from jsonb_array_elements(coalesce(d -> 'sources', '[]'::jsonb)) with ordinality as x(b, ord)
    order by ord
  on conflict (id) do nothing;

  insert into public.figures (id, type, titre, unite, axe_min, axe_max, note, sources, edition, fichier, alt, series)
    select f ->> 'id', f ->> 'type', coalesce(f ->> 'titre', ''), coalesce(f ->> 'unite', ''),
           (f ->> 'axe_min')::numeric, (f ->> 'axe_max')::numeric, coalesce(f ->> 'note', ''),
           coalesce(array(select jsonb_array_elements_text(coalesce(f -> 'sources', '[]'::jsonb))), '{}'),
           coalesce(f ->> 'edition', ''), coalesce(f ->> 'fichier', ''), coalesce(f ->> 'alt', ''),
           coalesce(f -> 'series', '[]'::jsonb)
    from jsonb_array_elements(coalesce(d -> 'figures', '[]'::jsonb)) with ordinality as x(f, ord)
    order by ord
  on conflict (id) do nothing;

  insert into public.editorial (sujet_id, type, auteur, initiales, age, texte, sources)
    select e ->> 'sujet_id', e ->> 'type', coalesce(e ->> 'auteur', ''), coalesce(e ->> 'initiales', ''),
           (e ->> 'age')::integer, e ->> 'texte',
           coalesce(array(select jsonb_array_elements_text(coalesce(e -> 'sources', '[]'::jsonb))), '{}')
    from jsonb_array_elements(coalesce(d -> 'editorial', '[]'::jsonb)) with ordinality as x(e, ord)
    order by ord;

  r := r || jsonb_build_object(
    'verbatims', (select count(*) from public.positions),
    'textes', (select count(*) from public.editorial),
    'sources', (select count(*) from public.sources),
    'figures', (select count(*) from public.figures));
  perform public._journal('import initial', r);
  return r;
end $$;

-- Export complet pour la sauvegarde Excel (mainteneurs).
create or replace function public.export_complet() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.est_mainteneur() then
    raise exception 'Action réservée aux mainteneurs.';
  end if;
  return jsonb_build_object(
    'candidats', coalesce((select jsonb_agg(c.nom order by c.ordre, c.nom) from public.candidats c), '[]'::jsonb),
    'thematiques', coalesce((
      select jsonb_agg(jsonb_build_object('nom', t.nom, 'sujets', coalesce((
               select jsonb_agg(jsonb_build_object(
                        'id', s.id, 'libelle', s.libelle, 'aussi_dans', to_jsonb(s.aussi_dans),
                        'positions', coalesce((select jsonb_object_agg(p.candidat, p.texte)
                                               from public.positions p where p.sujet_id = s.id), '{}'::jsonb))
                      order by s.ordre, s.id)
               from public.sujets s where s.thematique = t.nom), '[]'::jsonb))
             order by t.ordre, t.nom)
      from public.thematiques t), '[]'::jsonb),
    'editorial', coalesce((select jsonb_agg(to_jsonb(e) order by e.id) from public.editorial e), '[]'::jsonb),
    'sources', coalesce((select jsonb_agg(to_jsonb(s) order by s.ordre) from public.sources s), '[]'::jsonb),
    'figures', coalesce((select jsonb_agg(to_jsonb(f) order by f.ordre) from public.figures f), '[]'::jsonb),
    'depots', coalesce((
      select jsonb_agg(to_jsonb(x) || jsonb_build_object(
               'depose_par_pseudo', (select p.pseudo from public.profils p where p.id = x.depose_par),
               'traite_par_pseudo', (select p.pseudo from public.profils p where p.id = x.traite_par))
             order by x.id)
      from public.depots x), '[]'::jsonb),
    'journal', coalesce((select jsonb_agg(to_jsonb(j) order by j.id) from public.journal j), '[]'::jsonb));
end $$;

